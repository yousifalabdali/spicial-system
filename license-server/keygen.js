// Run once: creates the signing key pair.
//   private.pem  -> stays on YOUR server only (never ship it, never commit it)
//   ../electron/license-public-key.ts -> embedded in the app so it can verify keys offline
import { generateKeyPairSync } from 'node:crypto'
import { existsSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const dir = dirname(fileURLToPath(import.meta.url))
const privatePath = join(dir, 'private.pem')

if (existsSync(privatePath)) {
  console.error('private.pem already exists. Refusing to overwrite: every key already issued would stop working.')
  process.exit(1)
}

const { publicKey, privateKey } = generateKeyPairSync('ed25519')
writeFileSync(privatePath, privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600 })
const pub = publicKey.export({ type: 'spki', format: 'pem' })
writeFileSync(
  join(dir, '..', 'electron', 'license-public-key.ts'),
  `// Generated by license-server/keygen.js. Safe to ship: it can only verify keys, not create them.\nexport const PUBLIC_KEY_PEM = \`${pub}\`\n`,
)
console.log('Created private.pem and electron/license-public-key.ts')
console.log('Back up private.pem somewhere safe. If you lose it you cannot issue keys for new customers.')
